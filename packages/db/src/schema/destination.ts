// A trip's route: its ordered stops. Conventions: docs/architecture/data-model.md.
import {
  DESTINATION_NAME_MAX_LENGTH,
  DESTINATION_NOTE_MAX_LENGTH,
  LEG_MODES,
  MAX_NIGHTS_PER_DESTINATION,
} from '@globetrot/domain';
import { sql } from 'drizzle-orm';
import {
  boolean,
  char,
  check,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';
import type { PhotoRef } from './media';
import { trip } from './trip';

/** One place to see at a stop. Coordinates are optional: a spot can be just a name. */
export interface StopSpot {
  readonly name: string;
  readonly latitude: number | null;
  readonly longitude: number | null;
  readonly done: boolean;
}
/** One thing to do for a stop. */
export interface StopTodo {
  readonly text: string;
  readonly done: boolean;
}

const instant = (name: string) => timestamp(name, { withTimezone: true });

export const destination = pgTable(
  'destination',
  {
    /** UUIDv7 generated by the application. */
    id: uuid('id').primaryKey(),
    tripId: uuid('trip_id')
      .notNull()
      .references(() => trip.id, { onDelete: 'cascade' }),
    /** 0-based order on the route. The whole route is replaced together, so positions are always 0..n-1. */
    position: integer('position').notNull(),
    /** The client's stable key for the place (for example `geoapify:<id>` or `catalog:tokyo`). Not a foreign key. */
    placeKey: text('place_key').notNull(),
    name: text('name').notNull(),
    /** ISO 3166-1 alpha-2, optional. */
    countryCode: char('country_code', { length: 2 }),
    region: text('region'),
    latitude: doublePrecision('latitude').notNull(),
    longitude: doublePrecision('longitude').notNull(),
    nights: integer('nights').notNull().default(0),
    /** The person's note about this stop. Personal: never logged or audited. */
    note: text('note'),
    /** How they travel from this stop to the next (`LEG_MODES`); null when not set, and on the last stop. */
    legMode: text('leg_mode'),
    /** Marked visited by the person (their word, not a verification). The first one in a country stamps a visa. */
    visited: boolean('visited').notNull().default(false),
    /** Places to see at this stop, `StopSpot[]`. Personal: never logged or audited. */
    spots: jsonb('spots').$type<StopSpot[]>().notNull().default([]),
    /** Things to do for this stop, `StopTodo[]`. Personal: never logged or audited. */
    todos: jsonb('todos').$type<StopTodo[]>().notNull().default([]),
    /** The stop's own photos, `PhotoRef[]` (media the trip's owner uploaded). */
    photos: jsonb('photos').$type<PhotoRef[]>().notNull().default([]),
    createdAt: instant('created_at').defaultNow().notNull(),
    updatedAt: instant('updated_at').defaultNow().notNull(),
  },
  (table) => [
    index('destination_trip_id_position_idx').on(table.tripId, table.position),
    check('destination_position_valid', sql`${table.position} >= 0`),
    check(
      'destination_name_length',
      sql`char_length(${table.name}) between 1 and ${sql.raw(String(DESTINATION_NAME_MAX_LENGTH))}`,
    ),
    check('destination_place_key_length', sql`char_length(${table.placeKey}) between 1 and 200`),
    check('destination_country_format', sql`${table.countryCode} ~ '^[A-Z]{2}$'`),
    check('destination_latitude_range', sql`${table.latitude} between -90 and 90`),
    check('destination_longitude_range', sql`${table.longitude} between -180 and 180`),
    check(
      'destination_note_length',
      sql`char_length(${table.note}) between 1 and ${sql.raw(String(DESTINATION_NOTE_MAX_LENGTH))}`,
    ),
    check(
      'destination_leg_mode_valid',
      sql`${table.legMode} in (${sql.raw(LEG_MODES.map((mode) => `'${mode}'`).join(', '))})`,
    ),
    check('destination_spots_array', sql`jsonb_typeof(${table.spots}) = 'array'`),
    check('destination_todos_array', sql`jsonb_typeof(${table.todos}) = 'array'`),
    check('destination_photos_array', sql`jsonb_typeof(${table.photos}) = 'array'`),
    check(
      'destination_nights_range',
      sql`${table.nights} between 0 and ${sql.raw(String(MAX_NIGHTS_PER_DESTINATION))}`,
    ),
  ],
);
