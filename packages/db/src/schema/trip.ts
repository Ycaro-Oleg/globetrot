// Trips and the two cross-cutting tables the first mutations need (idempotency and audit).
// Conventions: docs/architecture/data-model.md. Rules: docs/product/business-rules.md (Trips).
import {
  DEFAULT_TRIP_STATUS,
  DEFAULT_TRIP_VISIBILITY,
  TRIP_STATUSES,
  TRIP_TITLE_MAX_LENGTH,
  TRIP_VISIBILITIES,
} from '@globetrot/domain';
import { sql, type AnyColumn, type SQL } from 'drizzle-orm';
import {
  char,
  check,
  date,
  index,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';
import { user } from './auth';

const instant = (name: string) => timestamp(name, { withTimezone: true });

/** `column IN ('a', 'b')` built from the same list the domain uses, so the two cannot drift apart. */
const oneOf = (column: AnyColumn, values: readonly string[]): SQL =>
  sql`${column} in (${sql.raw(values.map((value) => `'${value.replaceAll("'", "''")}'`).join(', '))})`;

export const trip = pgTable(
  'trip',
  {
    /** UUIDv7 generated by the application, so it is known before the insert. */
    id: uuid('id').primaryKey(),
    // `user.id` is Better Auth's text id, so the owner is text too. RESTRICT: deleting an account must never
    // silently destroy trips. Account deletion (retention rules) is specified separately.
    ownerId: text('owner_id')
      .notNull()
      .references(() => user.id, { onDelete: 'restrict' }),
    title: text('title').notNull(),
    /** Calendar date with no time zone; null until the user picks one. */
    startDate: date('start_date', { mode: 'string' }),
    currency: char('currency', { length: 3 }).notNull(),
    status: text('status').notNull().default(DEFAULT_TRIP_STATUS),
    visibility: text('visibility').notNull().default(DEFAULT_TRIP_VISIBILITY),
    /**
     * The community route post this trip was copied from, so the post can say "already copied" and a second copy
     * is not made. No foreign key: a deleted post leaves the copy alone.
     */
    copiedFromPostId: uuid('copied_from_post_id'),
    createdAt: instant('created_at').defaultNow().notNull(),
    updatedAt: instant('updated_at').defaultNow().notNull(),
  },
  (table) => [
    index('trip_owner_id_created_at_idx').on(table.ownerId, table.createdAt),
    index('trip_owner_id_copied_from_post_id_idx').on(table.ownerId, table.copiedFromPostId),
    check('trip_title_trimmed', sql`${table.title} = btrim(${table.title})`),
    check(
      'trip_title_length',
      sql`char_length(${table.title}) between 1 and ${sql.raw(String(TRIP_TITLE_MAX_LENGTH))}`,
    ),
    check('trip_currency_format', sql`${table.currency} ~ '^[A-Z]{3}$'`),
    check('trip_status_valid', oneOf(table.status, TRIP_STATUSES)),
    check('trip_visibility_valid', oneOf(table.visibility, TRIP_VISIBILITIES)),
  ],
);

/**
 * One row per `Idempotency-Key` an owner used. `fingerprint` is the canonical form of the request, so a retry
 * with the same key and payload is recognised and the same key with another payload is refused. `response` is
 * the stored result that a retry gets back. Rows are written in the same transaction as the work they guard.
 * Old rows can be deleted by a later cleanup job (they only matter for a retry window).
 */
export const idempotencyKey = pgTable(
  'idempotency_key',
  {
    ownerId: text('owner_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    key: text('key').notNull(),
    fingerprint: text('fingerprint').notNull(),
    response: jsonb('response'),
    createdAt: instant('created_at').defaultNow().notNull(),
  },
  (table) => [primaryKey({ columns: [table.ownerId, table.key] })],
);

/**
 * Append-only record of every mutation: who did what to which entity and when. `metadata` holds names of
 * fields that changed, never their values: no personal data. A database trigger rejects UPDATE, DELETE and
 * TRUNCATE (migration `0003_audit_event_append_only`). `actor_id` has no foreign key on purpose, so the
 * history outlives the account.
 */
export const auditEvent = pgTable(
  'audit_event',
  {
    id: uuid('id').primaryKey(),
    occurredAt: instant('occurred_at').notNull(),
    actorKind: text('actor_kind').notNull(),
    actorId: text('actor_id').notNull(),
    action: text('action').notNull(),
    entityType: text('entity_type').notNull(),
    entityId: text('entity_id').notNull(),
    metadata: jsonb('metadata').notNull().default({}),
  },
  (table) => [
    index('audit_event_entity_idx').on(table.entityType, table.entityId, table.occurredAt),
    index('audit_event_actor_idx').on(table.actorId, table.occurredAt),
  ],
);
